"""
Build rulebooks/library.yaml from a risk register in the sample layout
(Risk_Register_CAPA_Comprehensive_Anonymized.xlsx: sheet "Risk Register", two
header rows, prior / post treatment ratings).

    python build_risk_library.py <register.xlsx> [--version 1.0.0] [--out rulebooks/library.yaml]

Local tool: reads a file, writes a file, touches no database. A rebuilt library
is a new version; publishing it goes through gate G8 like any rulebook.
"""
from __future__ import annotations

import argparse
import datetime
import sys
from pathlib import Path

import openpyxl
import yaml

from regulatory_ingestion.risk import library_build as B

EXPECTED = {0: "sr. no.", 1: "risk type", 3: "division", 4: "risk control area", 6: "issue/risk description",
            7: "cia", 16: "risk mitigation actions", 17: "risk action", 20: "residual risk"}


def rows_from(path: Path) -> list[dict]:
    wb = openpyxl.load_workbook(path, read_only=True, data_only=True)
    if "Risk Register" not in wb.sheetnames:
        sys.exit(f"{path.name}: no 'Risk Register' sheet")
    rows = [r for r in wb["Risk Register"].iter_rows(values_only=True) if any(c not in (None, "") for c in r)]
    header_i = next((i for i, r in enumerate(rows[:5]) if str(r[0] or "").strip().lower() == "sr. no."), None)
    if header_i is None:
        sys.exit(f"{path.name}: no 'Sr. No.' header row in the first five rows")
    header = [str(c or "").strip().lower() for c in rows[header_i]]
    for i, name in EXPECTED.items():
        if i >= len(header) or header[i] != name:
            sys.exit(f"{path.name}: column {i + 1} is {header[i] if i < len(header) else None!r}, expected {name!r}"
                     " — a different register layout; map it before building")
    return [dict(zip(B.COLUMNS, r)) for r in rows[header_i + 1:]]


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("register")
    ap.add_argument("--version", default="1.0.0")
    ap.add_argument("--out", default=str(Path(__file__).resolve().parent / "rulebooks" / "library.yaml"))
    a = ap.parse_args()
    src = Path(a.register)
    templates = B.build(rows_from(src), src.name)
    doc = {
        "library": "library",
        "version": a.version,
        "status": "draft",
        "source": {"register": src.name, "rows": len(templates), "built_on": datetime.date.today().isoformat()},
        "notes": [
            "Templates bind to graph node types, not sectors: one library serves every organisation.",
            "benchmark = the register's own ratings. Never a score (decision D1).",
            "benchmark.prior was rated WITH existing controls (compare with residual); post = after planned treatment (target).",
            "seeds and base_likelihood are draft values from risk type and CIA; seed_status: draft costs confidence until reviewed.",
            "Treatment labels use ISO 31000 meanings (decision D3); rows whose numbers contradict their label are flagged.",
        ],
        "templates": templates,
    }
    Path(a.out).write_text(
        "# Generated by build_risk_library.py — edit the mapping in regulatory_ingestion/risk/library_build.py,\n"
        "# then rebuild, rather than editing templates here by hand.\n"
        + yaml.safe_dump(doc, sort_keys=False, allow_unicode=True, width=120))
    flagged = [t["id"] for t in templates if t["flags"]]
    by_theme: dict[str, int] = {}
    for t in templates:
        by_theme[t["theme"]] = by_theme.get(t["theme"], 0) + 1
    print(f"{len(templates)} templates → {a.out}")
    print("by theme:", dict(sorted(by_theme.items(), key=lambda x: -x[1])))
    print(f"flagged for review: {len(flagged)}", {t["id"]: t["flags"] for t in templates if t["flags"]})


if __name__ == "__main__":
    main()
