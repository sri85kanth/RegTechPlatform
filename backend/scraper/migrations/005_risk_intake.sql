-- =====================================================================
-- 005 · Risk module, Phase 2: what scoring needs to know, and who sets appetite
-- =====================================================================
--
-- Design: scraper/docs/risk-module-design.md §6 (intake), §7 (gates G1, G2), §8.
--
--   company_sites           where the company operates, and how big each site is
--   company_licences        licences as records (number, issuer, site, validity)
--   company_third_parties   vendors and outsourced services (no intake existed)
--   history_records         inspections, observations, CAPAs, incidents, recalls,
--                           complaints, litigation, penalties, warning letters
--   history_attestations    "none of kind K in the last N months", signed by a
--                           named person: absence of records is not a clean history
--   risk_appetite           leadership's appetite and tolerance per category,
--                           versioned and bitemporal (gate G1)
--   risk_governors          who, besides admins, may approve appetite
--   extracted_facts         facts proposed from documents or imports, waiting for
--                           a person to confirm, correct or reject them (gate G2)
--   fact_citations          where each proposed fact was read: file, page, quote
--
-- Every id is TEXT generated by the application, so the same DDL runs on
-- Postgres and on SQLite (the hermetic tests). JSON is stored as TEXT, as in
-- company_profile. All company tables: listed in tenancy.COMPANY_TABLES, and
-- copied into each workspace schema by `tenantctl.py sync`.
--
-- Additive only. Rollback: 005_risk_intake_rollback.sql.
-- =====================================================================

CREATE TABLE IF NOT EXISTS company_sites (
  id            TEXT PRIMARY KEY,
  name          TEXT NOT NULL,
  site_type     TEXT,                    -- hospital, clinic, laboratory, plant, office, warehouse, …
  address       TEXT,
  city          TEXT,
  state         TEXT,
  scale         TEXT,                    -- JSON: {"beds": 250, "ipd_per_year": …, "employees": …}
  service_lines TEXT,                    -- JSON list: ["radiology", "blood bank", …]
  status        TEXT NOT NULL DEFAULT 'CONFIRMED' CHECK (status IN ('PROPOSED','CONFIRMED')),
  source        TEXT,                    -- "entered by …", "confirmed from …"
  fact_id       TEXT,
  created_at    TEXT NOT NULL,
  updated_at    TEXT NOT NULL,
  retired_at    TEXT
);

CREATE TABLE IF NOT EXISTS company_licences (
  id            TEXT PRIMARY KEY,
  site_id       TEXT REFERENCES company_sites(id),
  kind          TEXT NOT NULL,           -- "Biomedical waste authorisation", "AERB licence", "Fire NOC", …
  issuer        TEXT,
  number        TEXT,
  valid_from    TEXT,
  valid_until   TEXT,
  conditions    TEXT,
  document_id   TEXT,
  status        TEXT NOT NULL DEFAULT 'CONFIRMED' CHECK (status IN ('PROPOSED','CONFIRMED')),
  source        TEXT,
  fact_id       TEXT,
  created_at    TEXT NOT NULL,
  updated_at    TEXT NOT NULL,
  retired_at    TEXT
);
CREATE INDEX IF NOT EXISTS idx_licences_site ON company_licences(site_id);

CREATE TABLE IF NOT EXISTS company_third_parties (
  id             TEXT PRIMARY KEY,
  name           TEXT NOT NULL,
  service        TEXT,                   -- what they do for us
  criticality    TEXT CHECK (criticality IS NULL OR criticality IN ('Critical','High','Medium','Low')),
  personal_data  INTEGER,                -- 1 shares personal data, 0 does not, NULL not known
  data_shared    TEXT,
  contract_ref   TEXT,
  contract_until TEXT,
  alternatives   TEXT,                   -- who else could do it; blank means none known
  site_ids       TEXT,                   -- JSON list; empty means every site
  status         TEXT NOT NULL DEFAULT 'CONFIRMED' CHECK (status IN ('PROPOSED','CONFIRMED')),
  source         TEXT,
  fact_id        TEXT,
  created_at     TEXT NOT NULL,
  updated_at     TEXT NOT NULL,
  retired_at     TEXT
);

CREATE TABLE IF NOT EXISTS history_records (
  id                   TEXT PRIMARY KEY,
  kind                 TEXT NOT NULL CHECK (kind IN ('INSPECTION','OBSERVATION','CAPA','INCIDENT','RECALL',
                                                     'COMPLAINT','LITIGATION','PENALTY','WARNING_LETTER')),
  occurred_on          TEXT NOT NULL,
  regulator            TEXT,
  site_id              TEXT REFERENCES company_sites(id),
  theme                TEXT,              -- a rulebook theme id, when known
  title                TEXT NOT NULL,
  description          TEXT,
  severity_as_recorded TEXT,              -- the source's own words ("major", "critical NC"), not ours
  outcome              TEXT,              -- inspections: clean, observations, adverse
  state                TEXT NOT NULL DEFAULT 'OPEN' CHECK (state IN ('OPEN','CLOSED')),
  closed_on            TEXT,
  due_on               TEXT,              -- CAPAs: when it should have closed
  requirement_ids      TEXT,              -- JSON list
  action_id            TEXT,              -- the CAPA in actions, when there is one
  document_id          TEXT,
  status               TEXT NOT NULL DEFAULT 'CONFIRMED' CHECK (status IN ('PROPOSED','CONFIRMED')),
  source               TEXT,
  fact_id              TEXT,
  created_at           TEXT NOT NULL,
  updated_at           TEXT NOT NULL,
  retired_at           TEXT
);
CREATE INDEX IF NOT EXISTS idx_history_kind ON history_records(kind, occurred_on);

CREATE TABLE IF NOT EXISTS history_attestations (
  id                TEXT PRIMARY KEY,
  kind              TEXT NOT NULL,       -- one of the history kinds, or ALL
  months            INTEGER NOT NULL CHECK (months > 0),
  site_id           TEXT REFERENCES company_sites(id),   -- NULL: every site
  statement         TEXT NOT NULL,
  attested_by_user  TEXT,
  attested_by_name  TEXT NOT NULL,
  designation       TEXT NOT NULL,
  attested_on       TEXT NOT NULL,
  document_id       TEXT,
  recorded_at       TEXT NOT NULL,
  superseded_at     TEXT
);

-- bitemporal: valid_from / valid_to = in force for the company;
--             recorded_at / superseded_at = known to us
CREATE TABLE IF NOT EXISTS risk_appetite (
  id                    TEXT PRIMARY KEY,
  version               INTEGER NOT NULL,
  status                TEXT NOT NULL CHECK (status IN ('DRAFT','APPROVED','RETURNED','SUPERSEDED')),
  content               TEXT NOT NULL,   -- JSON: categories, confidence_threshold, review_cadence, escalation_to, matrix
  note                  TEXT,
  created_by            TEXT,
  approved_by_user      TEXT,
  approver_name         TEXT,
  approver_designation  TEXT,
  minutes_document_id   TEXT,
  valid_from            TEXT,
  valid_to              TEXT,
  recorded_at           TEXT NOT NULL,
  superseded_at         TEXT
);
CREATE INDEX IF NOT EXISTS idx_appetite_status ON risk_appetite(status, version);

CREATE TABLE IF NOT EXISTS risk_governors (
  user_id      TEXT PRIMARY KEY,
  designation  TEXT,
  granted_by   TEXT NOT NULL,
  granted_at   TEXT NOT NULL,
  revoked_at   TEXT
);

CREATE TABLE IF NOT EXISTS extracted_facts (
  id               TEXT PRIMARY KEY,
  fact_key         TEXT NOT NULL,        -- site, licence, third_party, history, profile.beds
  dedupe_key       TEXT NOT NULL UNIQUE, -- the same fact read twice is proposed once
  value            TEXT NOT NULL,        -- JSON, as read
  status           TEXT NOT NULL DEFAULT 'PROPOSED'
                     CHECK (status IN ('PROPOSED','CONFIRMED','CORRECTED','REJECTED')),
  corrected_value  TEXT,                 -- JSON, as the person set it
  extracted_by     TEXT NOT NULL,        -- rule:<name>, llm:<model>, import:<source>
  confidence       INTEGER,
  note             TEXT,
  target_table     TEXT,                 -- where a confirmed fact landed
  target_id        TEXT,
  decided_by       TEXT,
  decided_at       TEXT,
  created_at       TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_facts_status ON extracted_facts(status, fact_key);

CREATE TABLE IF NOT EXISTS fact_citations (
  id           TEXT PRIMARY KEY,
  fact_id      TEXT NOT NULL REFERENCES extracted_facts(id) ON DELETE CASCADE,
  document_id  TEXT,
  file_name    TEXT,
  page         INTEGER,
  section      TEXT,
  quote        TEXT
);
CREATE INDEX IF NOT EXISTS idx_citations_fact ON fact_citations(fact_id);
