"""
Embed the NABH Guidebook (6th Ed.) into the RAG store (company_brain_rag.chunks),
linked to regulation nabh-hospital-6th-edition-2025, so /api/rag search and the
Knowledge Search page return it.

    python nabh6_guidebook_rag.py <hosp6_gb.json> <ocr.txt>

Two kinds of chunk, source_table 'guidebook':
  <REG>-gb-oe-<code>#n   one per objective element: standard text + its interpretation
  <REG>-gb-p<NNNN>#n     one per page of OCR text (catches tables, annexures, glossary)
Documents are embedded WITHOUT the query prefix, normalised, bge-base-en-v1.5
(same as rag.index). Inserts go in with the HNSW index live (no rebuild);
rag.prune() then drops superseded versions and VACUUMs for recall.
These rows are not regenerated by rag.index(): the OCR JSON is their source.
"""
from __future__ import annotations

import json
import re
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from regulatory_ingestion import rag                               # noqa: E402

REG = "nabh-hospital-6th-edition-2025"
TITLE = "NABH Guidebook to Accreditation Standards for Hospitals, 6th Edition"
URL = ("https://nabh-portal-live.s3.ap-south-1.amazonaws.com/wp-content/uploads/2025/07/13111206/"
       "NABH-Hospital-Accreditation-Standard-6th-Edition-January-2025.pdf")
APP = f"/regulation/{REG}"


def slug(s: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-")


def main() -> None:
    stds = json.loads(Path(sys.argv[1]).read_text())["standards"]
    ocr = Path(sys.argv[2]).read_text(errors="ignore")
    chunks = []
    for s in stds:
        for e in s["elements"]:
            code = e["code"].rstrip(".")
            head = f"{TITLE} — {code} ({e['category']}) · {s['chapter_name']}"
            body = f"Standard {s['code'].rstrip('.')}: {s['statement']}\nObjective element {code}: {e['text']}"
            if e.get("interpretation"):
                body += f"\nInterpretation: {e['interpretation']}"
            for i, piece in enumerate(rag.split(body)):
                chunks.append({"source_id": f"{REG}-gb-oe-{slug(code)}#{i}", "section_number": code,
                               "title": f"{TITLE} — {code}", "content": f"{head}\n{piece}"})
    for m in re.finditer(r"<<<PAGE (\d+)>>>\n(.*?)(?=<<<PAGE \d+>>>|\Z)", ocr, re.S):
        page, text = int(m.group(1)), re.sub(r"[ \t]+", " ", m.group(2)).strip()
        if len(text) < 80:
            continue
        head = f"{TITLE} — page {page}"
        for i, piece in enumerate(rag.split(text)):
            chunks.append({"source_id": f"{REG}-gb-p{page:04d}#{i}", "section_number": None,
                           "title": head, "content": f"{head}\n{piece}"})
    print(f"chunks {len(chunks)} (elements + pages)", flush=True)

    t = time.time()
    model = rag.model()
    print(f"model loaded in {time.time() - t:.0f}s", flush=True)
    t = time.time()
    vecs = model.encode([c["content"] for c in chunks], batch_size=64, normalize_embeddings=True,
                        show_progress_bar=False)
    print(f"encoded in {time.time() - t:.0f}s", flush=True)

    pcon = rag.connect_pg()
    n = 0
    with pcon.cursor() as cur:
        for c, v in zip(chunks, vecs):
            cur.execute(
                """INSERT INTO chunks (corpus, source_table, source_id, regulation_id, entity_id, domain, title,
                     section_number, content, token_estimate, url, app_path, content_hash, embedding)
                   VALUES ('regulatory','guidebook',%s,%s,NULL,'NABH',%s,%s,%s,%s,%s,%s,%s,%s)
                   ON CONFLICT (source_table, source_id, content_hash) DO NOTHING""",
                (c["source_id"], REG, c["title"], c["section_number"], c["content"], len(c["content"]) // 4,
                 URL, APP, rag._h(c["content"]), v))   # numpy vector, adapted by pgvector as in rag.index()
            n += cur.rowcount
        cur.execute("""INSERT INTO index_runs (corpus, model, dims, chunks_seen, chunks_written, finished_at, detail)
                       VALUES ('regulatory', %s, %s, %s, %s, now(), 'NABH 6th Ed. guidebook (OCR)')""",
                    (rag.MODEL_NAME, rag.DIMS, len(chunks), n))
    pcon.commit()
    print(f"inserted {n}", flush=True)
    print("prune:", rag.prune(pcon), flush=True)


if __name__ == "__main__":
    main()
